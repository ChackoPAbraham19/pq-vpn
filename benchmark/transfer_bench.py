#!/usr/bin/env python3
"""transfer_bench.py — bulk transfer through the tunnel, across sizes, hashed in flight.

Replaces a download-to-a-file benchmark that had two problems:

  * it wrote the received bytes to disk, so at the measured 0.5-1.3 Gbps the
    filesystem could be slower than the tunnel and the figure was partly a disk
    benchmark;
  * it measured one size (100 MB) once, which cannot separate the fixed cost of
    opening a connection from the sustained rate of the relay.

Here the server streams generated bytes and the client hashes and discards them,
so nothing is stored and size is bounded by time rather than free space. Both
ends derive the same stream from one seed, so the client can compare what it
received against what should have arrived without the hash ever crossing the
wire.

Connection setup and the transfer itself are timed separately: small transfers
are expected to be dominated by setup (where post-quantum is worse, its
handshake being larger) and big ones by the relay (where the modes should
converge). Reporting one total would hide exactly that.

    # inside the server namespace
    transfer_bench.py --serve 0.0.0.0 9998

    # from the client
    transfer_bench.py --client 10.8.0.1 9998 --mode pqc --out results/x.csv

Writes mode,size_bytes,rep,connect_ms,transfer_ms,total_ms,mbps,sha256_ok.
"""
import argparse
import csv
import hashlib
import os
import random
import socket
import statistics
import struct
import sys
import time

BLOCK_BITS = 20                      # 1 MiB generated block, repeated to fill
BLOCK = 1 << BLOCK_BITS
SEED = 0x50515650                    # "PQVP"; both ends derive the same stream
HEADER = struct.Struct('!Q')         # requested size, in bytes

# Seven points over six orders of magnitude, log-spaced so the curve is
# readable. Small sizes expose setup cost, large ones the sustained ceiling.
DEFAULT_SIZES = [1 << 10, 100 << 10, 1 << 20, 10 << 20, 100 << 20, 500 << 20, 1 << 30]
DEFAULT_REPS = 3


def _block() -> bytes:
    """The 1 MiB block both ends repeat. Deterministic from SEED.

    Repetition is harmless here: TLS 1.3 does not compress, and neither does
    the framing, so the bytes on the wire cost the same as random ones.
    """
    return random.Random(SEED).randbytes(BLOCK)


def expected_digest(size: int, block: bytes) -> str:
    h = hashlib.sha256()
    whole, rest = divmod(size, BLOCK)
    for _ in range(whole):
        h.update(block)
    if rest:
        h.update(block[:rest])
    return h.hexdigest()


def serve(host: str, port: int):
    """Stream `size` bytes per connection, forever. One connection per trial."""
    block = _block()
    srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    srv.bind((host, port))
    srv.listen(8)
    print(f'[transfer] serving on {host}:{port}', flush=True)
    while True:
        try:
            conn, _ = srv.accept()
        except OSError:
            break
        try:
            raw = b''
            while len(raw) < HEADER.size:
                chunk = conn.recv(HEADER.size - len(raw))
                if not chunk:
                    raise ConnectionError('client hung up before sending a size')
                raw += chunk
            (size,) = HEADER.unpack(raw)
            sent = 0
            while sent < size:
                n = min(BLOCK, size - sent)
                conn.sendall(block[:n] if n < BLOCK else block)
                sent += n
        except (OSError, ConnectionError) as e:
            print(f'[transfer] connection failed: {e}', file=sys.stderr, flush=True)
        finally:
            try:
                conn.close()
            except OSError:
                pass


def one_trial(host: str, port: int, size: int, block: bytes) -> tuple:
    """(connect_ms, transfer_ms, sha256_ok) for a single transfer."""
    t0 = time.perf_counter()
    sock = socket.create_connection((host, port), timeout=30)
    t1 = time.perf_counter()
    try:
        sock.sendall(HEADER.pack(size))
        h = hashlib.sha256()
        got = 0
        # A view onto one buffer, so a 1 GB transfer allocates once rather than
        # once per read.
        buf = bytearray(1 << 16)
        view = memoryview(buf)
        # Scale the deadline with size: a flat timeout fails the big transfers
        # on a slow link and hides a real result as an error.
        sock.settimeout(max(30.0, size / (1 << 20) * 0.5))
        while got < size:
            n = sock.recv_into(view, min(len(buf), size - got))
            if not n:
                raise ConnectionError(f'stream ended at {got}/{size} bytes')
            h.update(view[:n])
            got += n
        t2 = time.perf_counter()
    finally:
        sock.close()
    ok = h.hexdigest() == expected_digest(size, block)
    return (t1 - t0) * 1000.0, (t2 - t1) * 1000.0, ok


def human(size: int) -> str:
    for unit, div in (('GB', 1 << 30), ('MB', 1 << 20), ('KB', 1 << 10)):
        if size >= div:
            value = size / div
            return f'{value:.0f}{unit}' if value == int(value) else f'{value:.1f}{unit}'
    return f'{size}B'


def run_client(host, port, mode, sizes, reps, out_path):
    block = _block()
    rows = []
    print(f'=== transfer sweep: {mode} ({len(sizes)} sizes x {reps} reps) ===')
    for size in sizes:
        samples = []
        for rep in range(1, reps + 1):
            try:
                connect_ms, transfer_ms, ok = one_trial(host, port, size, block)
            except (OSError, ConnectionError) as e:
                print(f'  {human(size):>7s} rep {rep}: FAILED ({e})', file=sys.stderr)
                rows.append({'mode': mode, 'size_bytes': size, 'rep': rep,
                             'connect_ms': '', 'transfer_ms': '', 'total_ms': '',
                             'mbps': '', 'sha256_ok': 'err'})
                continue
            total_ms = connect_ms + transfer_ms
            mbps = (size * 8) / (transfer_ms / 1000.0) / 1e6 if transfer_ms > 0 else 0.0
            samples.append((total_ms, mbps, ok))
            rows.append({'mode': mode, 'size_bytes': size, 'rep': rep,
                         'connect_ms': f'{connect_ms:.2f}',
                         'transfer_ms': f'{transfer_ms:.2f}',
                         'total_ms': f'{total_ms:.2f}',
                         'mbps': f'{mbps:.1f}',
                         'sha256_ok': 'yes' if ok else 'no'})
        if samples:
            med_total = statistics.median(t for t, _, _ in samples)
            med_mbps = statistics.median(m for _, m, _ in samples)
            all_ok = all(o for _, _, o in samples)
            print(f'  {human(size):>7s}  median {med_total:9.2f} ms  '
                  f'{med_mbps:8.1f} Mbps  sha256={"ok" if all_ok else "MISMATCH"}')

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, 'w', newline='') as fh:
        w = csv.DictWriter(fh, lineterminator='\n', fieldnames=['mode', 'size_bytes', 'rep', 'connect_ms',
                                           'transfer_ms', 'total_ms', 'mbps', 'sha256_ok'])
        w.writeheader()
        w.writerows(rows)
    bad = [r for r in rows if r['sha256_ok'] != 'yes']
    print(f'  -> {out_path}')
    if bad:
        print(f'  WARNING: {len(bad)} trial(s) did not verify', file=sys.stderr)
        return 1
    return 0


def parse_sizes(spec: str) -> list:
    """'1K 10M 1G' -> byte counts. Env/CLI friendly."""
    out = []
    for token in spec.replace(',', ' ').split():
        token = token.strip().upper()
        mult = 1
        if token.endswith('K'):
            mult, token = 1 << 10, token[:-1]
        elif token.endswith('M'):
            mult, token = 1 << 20, token[:-1]
        elif token.endswith('G'):
            mult, token = 1 << 30, token[:-1]
        out.append(int(float(token) * mult))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--serve', nargs=2, metavar=('HOST', 'PORT'))
    ap.add_argument('--client', nargs=2, metavar=('HOST', 'PORT'))
    ap.add_argument('--mode', default='unknown')
    ap.add_argument('--sizes', default=os.environ.get('PQVPN_BENCH_SIZES', ''))
    ap.add_argument('--reps', type=int,
                    default=int(os.environ.get('PQVPN_BENCH_REPS', DEFAULT_REPS)))
    ap.add_argument('--out', default=None)
    args = ap.parse_args()

    if args.serve:
        serve(args.serve[0], int(args.serve[1]))
        return 0
    if not args.client:
        ap.error('one of --serve or --client is required')

    sizes = parse_sizes(args.sizes) if args.sizes else DEFAULT_SIZES
    out = args.out or os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   'results', f'file_transfer_{args.mode}.csv')
    return run_client(args.client[0], int(args.client[1]), args.mode,
                      sizes, args.reps, out)


if __name__ == '__main__':
    sys.exit(main())
